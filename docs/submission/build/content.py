TITLE = "把司機用在刀口上：綠線公車駕駛人力再配置"

ABSTRACT = ("捷運綠線北段G11至G15b預計115年底通車，沿線公車面臨平行競爭或轉型接駁之調整，"
            "而駕駛人力不足為市府指出之瓶頸。本研究以TDX開放資料建立路線重疊、接駁可及性與駕駛人力換算指標，"
            "估算裁切平行路段後可再配置之駕駛班次，並以可一車直達車站之長者人口檢視公平性，"
            "建立可供分階段通車重複使用之決策工具。")

